#!/bin/bash
# Builds mGBA's core as a static library (no frontends, no Qt, no external dependencies)
# from the untouched mgba/ submodule, applying patches/*.patch to a scratch copy if any exist.
# Output: build/libmgba/install/{lib/libmgba.a,include/}
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SRC="$ROOT/mgba"
OUT="$ROOT/build/libmgba"
CONFIG="${CONFIG:-Release}"

[ -f "$SRC/CMakeLists.txt" ] || { echo "mgba/ is empty: git submodule update --init" >&2; exit 1; }

# --if-needed (Xcode's pre-build step): skip when the library matches the submodule commit and the patches.
STAMP="$OUT/install/.stamp"
WANT="$(git -C "$SRC" rev-parse HEAD) $CONFIG $({ cat "$ROOT"/patches/*.patch 2>/dev/null || true; } | shasum | cut -c1-12)"
if [ "${1:-}" = "--if-needed" ] && [ -f "$OUT/install/lib/libmgba.a" ] && [ "$(cat "$STAMP" 2>/dev/null)" = "$WANT" ]; then
	echo "libmgba is up to date ($WANT)"
	exit 0
fi

shopt -s nullglob
PATCHES=("$ROOT"/patches/*.patch)
if [ ${#PATCHES[@]} -gt 0 ]; then
	# Patches go onto an APFS clone of the submodule so mgba/ itself stays clean.
	echo "== applying ${#PATCHES[@]} patch(es) to build/libmgba/src"
	rm -rf "$OUT/src"; mkdir -p "$OUT"
	cp -cR "$SRC" "$OUT/src"
	for p in "${PATCHES[@]}"; do git -C "$OUT/src" apply --verbose "$p"; done
	SRC="$OUT/src"
fi

echo "== configure ($CONFIG, arm64, mgba $(git -C "$ROOT/mgba" describe --always --tags))"
cmake -S "$SRC" -B "$OUT/cmake" -G Ninja \
	-DCMAKE_BUILD_TYPE="$CONFIG" \
	-DCMAKE_OSX_ARCHITECTURES=arm64 \
	-DCMAKE_OSX_DEPLOYMENT_TARGET=14.0 \
	-DCMAKE_INSTALL_PREFIX="$OUT/install" \
	-DLIBMGBA_ONLY=ON \
	-DM_CORE_GB=ON -DM_CORE_GBA=ON
echo "== build"
cmake --build "$OUT/cmake"
echo "== install"
rm -rf "$OUT/install"
cmake --install "$OUT/cmake" --component libmgba >/dev/null 2>&1 || true
cmake --install "$OUT/cmake" >/dev/null
ls -l "$OUT/install/lib/libmgba.a"

# mGBA's flags.h is configured before some feature defines are set (ENABLE_DIRECTORIES is missing
# from it), so struct layouts would differ from the library's. Write the library's real compile
# defines into a header that the player includes before any mGBA header.
DEFS_H="$OUT/install/include/mgba-build-defines.h"
{
	echo "/* Generated by scripts/build-libmgba.sh from the libmgba compile line. Do not edit. */"
	echo "#ifndef MGBA_BUILD_DEFINES_H"
	echo "#define MGBA_BUILD_DEFINES_H"
	grep -m1 '^  DEFINES = ' "$OUT/cmake/build.ninja" | sed 's/^  DEFINES = //' | tr ' ' '\n' | sed -n 's/^-D//p' |
		grep -v '^_' | while IFS='=' read -r name value; do
			echo "#ifndef $name"
			echo "#define $name${value:+ $value}"
			echo "#endif"
		done
	echo "#include <mgba/flags.h>"
	echo "#endif"
} > "$DEFS_H"
echo "$WANT" > "$STAMP"
echo "== defines ($DEFS_H)"
grep -c '^#define' "$DEFS_H"
